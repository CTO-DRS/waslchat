/// حدود الوسائط الموحّدة — مصدر واحد للحقيقة (المرحلة 12: 0.28.0).
///
/// كان حد الملفات متناثراً في أربعة مواضع (chat_screen وstatus_service)
/// بقيمة مضروبة يدوياً ونصّ عربي مكرر — أي رفع مستقبلي للحد (بترقية
/// التخزين: Supabase Pro بقرار المالك وفق GRAND_PLAN) كان سيتطلب لمس
/// كل موضع بايتاً بايتاً وأي إفلات واحد يكذب للمستخدم.
///
/// **الحد الفعلي اليوم بقي 24 م.ب كما هو** — القيود الخادمية (Storage
/// bucket وRLS) ما تزال تحكم ما يتلقاه الخادم، والرفع يتطلب قرار المالك
/// وترحيل تعديل الحد الخادمي وثق هذا الملف في كل مكان يذكر الحد.
///
/// الإفصاح الصادق: الخادم لا يرى المحتوى أبداً (الوسائط مشفّرة بالبايتات
/// قبل الرفع) لكنه يرى الحجم — الحد هنا حماية للطبقة المجانية أولاً.
class MediaLimits {
  MediaLimits._();

  /// الحد الأقصى لأي وسيط يُرسل في المحادثات (فيديو أو ملف) بالبايتات.
  static const int maxMediaBytes = 24 * 1024 * 1024;

  /// الحد الأقصى لحالة فيديو/صورة (المرحلة 11 ب — نفس الحد وقتها).
  static const int maxStatusBytes = 24 * 1024 * 1024;

  /// حد حالة الفيديو الصارم (0.27.0): 12 م.ب — حارس النشر.
  static const int maxStatusVideoBytes = 12 * 1024 * 1024;

  /// النص العربي الموحّد للحد — مكان واحد يتغير مع الحد نفسه.
  static const String maxMediaText = '24 ميغابايت';

  /// التسمية العربية للحد بحجمه المحسوب (للأدوات والتقارير).
  static String get maxMediaLabel =>
      '${(maxMediaBytes / (1024 * 1024)).toStringAsFixed(0)} م.ب';
}
